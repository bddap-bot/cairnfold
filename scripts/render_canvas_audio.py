#!/usr/bin/env python3
"""Offline same-motion audio comparison; not a device capture. Run under nix-shell with an output directory."""
import json
from pathlib import Path
import subprocess
import sys
import wave
import numpy as np
from compose import SR

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    data = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(data, np.float32)


def write(path, x):
    with wave.open(str(path), 'wb') as out:
        out.setparams((1, 2, SR, 0, 'NONE', 'not compressed'))
        out.writeframes((np.clip(x, -1, 1) * 32767).astype('<i2').tobytes())


def trace(t):
    if 0.5 <= t < 2:
        return 0.04, 0.25
    if 2.5 <= t < 4:
        return 0.18, 0.8
    if 4.5 <= t < 6:
        return 0.09, 0.45
    return 0.0, 0.8


def render(profile):
    rng = np.random.default_rng(8801)
    old = profile == 'old'
    clips = [read(ROOT / f'tests/fixtures/canvas-audio/brush{i}.ogg') for i in range(4)] if old else [read(ROOT / f'game/audio/charcoal/{profile}{i}.ogg') for i in range(8)]
    result = np.zeros(7 * SR)
    previous = -1
    due = 0.0
    for frame in range(420):
        t = frame / 60
        speed, pressure = trace(t)
        if not old and speed == 0:
            # Runtime stops both voices on the first stationary frame.
            result[int(t * SR):] = 0
            due = t
            continue
        if t < due or t < 0.5 or t >= 6:
            continue
        if old:
            # Old charcoal cue: moving samples up to 40Hz, stationary deposits at 10Hz.
            due = t + (0.025 if speed else 0.1)
            index = int(rng.integers(4))
            pitch = 0.8 * rng.uniform(0.88, 1.12)
            gain = 10 ** ((-18 + rng.uniform(-1.5, 1)) / 20)
        else:
            due = t + 0.1
            index = (previous + 1 + int(rng.integers(7))) % 8
            previous = index
            pitch = min(1.05, 0.85 + speed * 0.3)
            gain = 10 ** (-8 / 20) * (0.15 + 0.35 * pressure) * min(1, speed / 0.12)
        x = clips[index]
        x = np.interp(np.arange(0, len(x) - 1, pitch), np.arange(len(x)), x) * gain
        start = int(t * SR)
        result[start:start + len(x)] += x[:len(result) - start]
    return result


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    parts = []
    metrics = {}
    for i, profile in enumerate(('old', 'soft', 'paper', 'dark')):
        x = render(profile)
        write(out / f'{i:02d}-{profile}.wav', x)
        parts.extend((x, np.zeros(SR)))
        metrics[profile] = {'peak_dbfs': float(20 * np.log10(max(np.abs(x).max(), 1e-12))), 'rms_dbfs': float(20 * np.log10(max(np.sqrt(np.mean(x*x)), 1e-12)))}
    write(out / 'comparison-old-soft-paper-dark.wav', np.concatenate(parts))
    write(out / 'brushes-silent.wav', np.zeros(7 * SR))
    (out / 'measurements.json').write_text(json.dumps(metrics, indent=2) + '\n')
    (out / 'README.txt').write_text('Offline audio comparison, not a headset capture. Order: old charcoal, soft (default candidate), paper, dark. Each uses the same 7-second trace: slow/light stroke 0.5–2 s, pause, fast/firm 2.5–4 s, pause, medium 4.5–6 s, stop. Old sample-driven cue also plays during stationary deposits; new cues stop on pauses. Levels reproduce cue gains at reference distance, with no loudness normalization. Wet and oil brush contact are silent (brushes-silent.wav). No human listening preference or device performance is claimed. Source/licence: game/audio/charcoal/source.json; generated by scripts/render_canvas_audio.py.\n')


if __name__ == '__main__':
    main()
